#!/usr/bin/env python3
"""Generate src/images/JesterLogo120.h, Jester's boot and sleep logo.

The logo is U+274D SHADOWED WHITE CIRCLE drawn as geometry: a white disc with a
black outline and a black crescent shadow straight to the right. Output format
matches the CrossInk Logo120.h it replaced: 120x120, 1 bit per pixel, rows of 15 bytes,
most significant bit first, 1 = white, 0 = black.

Usage: python3 scripts/generate_jester_logo.py
"""

from pathlib import Path

SIZE = 120
SCALE = 8  # supersampling factor for smooth edges
# drawImage() copies bytes in panel order without rotating them, and the panel
# is landscape: on the portrait boot/sleep screens the stored image appears
# turned 90 degrees clockwise. U+274D has its shadow straight to the right, so
# the shadow is stored straight up (-y), which shows straight to the right.
CENTER_X = 60.0
CENTER_Y = 64.0  # disc centre; leaves room for the shadow inside 120 px
RADIUS = 48.0
OUTLINE = 5.0
SHADOW_OFFSET = 7.0

OUT = Path(__file__).resolve().parent.parent / "src" / "images" / "JesterLogo120.h"


def is_black(x: float, y: float) -> bool:
    dx, dy = x - CENTER_X, y - CENTER_Y
    d = (dx * dx + dy * dy) ** 0.5
    if d <= RADIUS:
        return d >= RADIUS - OUTLINE  # outline ring; inside stays white
    sx, sy = x - CENTER_X, y - CENTER_Y + SHADOW_OFFSET
    return (sx * sx + sy * sy) ** 0.5 <= RADIUS  # shadow crescent


def pixel_black(px: int, py: int) -> bool:
    hits = 0
    for sy in range(SCALE):
        for sx in range(SCALE):
            if is_black(px + (sx + 0.5) / SCALE, py + (sy + 0.5) / SCALE):
                hits += 1
    return hits * 2 >= SCALE * SCALE


def main() -> None:
    data = []
    for y in range(SIZE):
        for xb in range(SIZE // 8):
            byte = 0
            for bit in range(8):
                if not pixel_black(xb * 8 + bit, y):
                    byte |= 0x80 >> bit
            data.append(byte)

    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// Generated by scripts/generate_jester_logo.py; do not edit by hand.",
        "// Jester logo, U+274D SHADOWED WHITE CIRCLE, 120x120px",
        "static const uint8_t JesterLogo120[] = {",
    ]
    for i in range(0, len(data), 19):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 19]) + ",")
    lines.append("};")
    lines.append("")
    lines.append('static_assert(sizeof(JesterLogo120) == 1800, "JesterLogo120 must be exactly 120x120 / 8 bytes");')
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
