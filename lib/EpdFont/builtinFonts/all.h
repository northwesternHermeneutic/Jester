#pragma once

#include <builtinFonts/ui_symbols_10.h>

// Jester ships a single built-in family: IBM Plex Serif with the semibold
// swap. The regular/italic slots hold SemiBold/SemiBold Italic so body text is
// bolder for legibility; the bold/bolditalic slots hold Regular/Italic so
// emphasis still reads as distinct from body text.
//
// Size 12 carries the full reading coverage and is the default for the reader,
// the UI title slot and the dictionary. Sizes 8, 10 and 14 carry base coverage
// (ASCII plus General Punctuation) for UI text and as selectable reader sizes.
// Wider coverage is added by the user as SD-card .cpfont files.
#include <builtinFonts/plexserif_8_bold.h>
#include <builtinFonts/plexserif_8_bolditalic.h>
#include <builtinFonts/plexserif_8_italic.h>
#include <builtinFonts/plexserif_8_regular.h>
#include <builtinFonts/plexserif_10_bold.h>
#include <builtinFonts/plexserif_10_bolditalic.h>
#include <builtinFonts/plexserif_10_italic.h>
#include <builtinFonts/plexserif_10_regular.h>
#include <builtinFonts/plexserif_12_bold.h>
#include <builtinFonts/plexserif_12_bolditalic.h>
#include <builtinFonts/plexserif_12_italic.h>
#include <builtinFonts/plexserif_12_regular.h>
#include <builtinFonts/plexserif_14_bold.h>
#include <builtinFonts/plexserif_14_bolditalic.h>
#include <builtinFonts/plexserif_14_italic.h>
#include <builtinFonts/plexserif_14_regular.h>
